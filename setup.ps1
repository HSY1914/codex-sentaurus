[CmdletBinding()]
param(
    [string]$HostAddress,
    [ValidateRange(1, 65535)]
    [int]$Port,
    [string]$UserName,
    [string]$IdentityFile,
    [string]$VmName,
    [string]$VmxPath,
    [string]$VmrunPath,
    [switch]$CreateKey,
    [switch]$SkipAuthorize
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$baseConfigPath = Join-Path $root 'connection.json'
$localConfigPath = Join-Path $root 'connection.local.json'
$localSshConfigPath = Join-Path $root 'ssh_config.local'
$knownHostsPath = Join-Path $root 'known_hosts'

function Read-JsonObject([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path)) { return [pscustomobject]@{} }
    return Get-Content -LiteralPath $Path -Raw -Encoding UTF8 | ConvertFrom-Json
}

function Get-ConfigValue([object]$Local, [object]$Base, [string]$Name, [string]$Fallback = '') {
    $localProperty = $Local.PSObject.Properties[$Name]
    if ($localProperty -and -not [string]::IsNullOrWhiteSpace([string]$localProperty.Value)) {
        return [string]$localProperty.Value
    }
    $baseProperty = $Base.PSObject.Properties[$Name]
    if ($baseProperty -and -not [string]::IsNullOrWhiteSpace([string]$baseProperty.Value)) {
        return [string]$baseProperty.Value
    }
    return $Fallback
}

function Read-Default([string]$Prompt, [string]$Default) {
    if ([string]::IsNullOrWhiteSpace($Default)) { return (Read-Host $Prompt) }
    $answer = Read-Host "$Prompt [$Default]"
    if ([string]::IsNullOrWhiteSpace($answer)) { return $Default }
    return $answer
}

function Expand-PathValue([string]$Value) {
    if ([string]::IsNullOrWhiteSpace($Value)) { return $Value }
    $expanded = [Environment]::ExpandEnvironmentVariables($Value)
    if ($expanded -match '^[~][\\/]') {
        $expanded = Join-Path $env:USERPROFILE $expanded.Substring(2)
    }
    return [IO.Path]::GetFullPath($expanded)
}

$base = Read-JsonObject $baseConfigPath
$local = Read-JsonObject $localConfigPath
$HostAddress = if ($PSBoundParameters.ContainsKey('HostAddress')) { $HostAddress } else {
    Read-Default 'Sentaurus VM host address' (Get-ConfigValue $local $base 'host' '192.168.110.200')
}
$portText = if ($PSBoundParameters.ContainsKey('Port')) { [string]$Port } else {
    Read-Default 'SSH port' (Get-ConfigValue $local $base 'port' '22')
}
if (-not [int]::TryParse($portText, [ref]$Port) -or $Port -lt 1 -or $Port -gt 65535) {
    throw 'Invalid SSH port.'
}
$UserName = if ($PSBoundParameters.ContainsKey('UserName')) { $UserName } else {
    Read-Default 'Linux username' (Get-ConfigValue $local $base 'username' 'TCAD2022')
}
$defaultIdentity = Join-Path $env:USERPROFILE '.ssh\id_ed25519_sentaurus_codex'
$IdentityFile = if ($PSBoundParameters.ContainsKey('IdentityFile')) { $IdentityFile } else {
    Read-Default 'SSH private-key path' (Get-ConfigValue $local $base 'identityFile' $defaultIdentity)
}
$IdentityFile = Expand-PathValue $IdentityFile
$VmName = if ($PSBoundParameters.ContainsKey('VmName')) { $VmName } else { Get-ConfigValue $local $base 'vmName' 'sentaurus TCAD2022' }
$VmxPath = if ($PSBoundParameters.ContainsKey('VmxPath')) { $VmxPath } else { Get-ConfigValue $local $base 'vmxPath' '' }
$VmrunPath = if ($PSBoundParameters.ContainsKey('VmrunPath')) { $VmrunPath } else { Get-ConfigValue $local $base 'vmrunPath' '' }

if ($HostAddress -notmatch '^[a-zA-Z0-9][a-zA-Z0-9.:-]*$') { throw 'Invalid host address.' }
if ($UserName -notmatch '^[a-zA-Z_][a-zA-Z0-9_.-]*\$?$') { throw 'Invalid Linux username.' }

$ssh = (Get-Command ssh.exe -ErrorAction Stop).Source
$sshKeygen = (Get-Command ssh-keygen.exe -ErrorAction Stop).Source
$identityDirectory = Split-Path -Parent $IdentityFile
New-Item -ItemType Directory -Force -Path $identityDirectory | Out-Null

if (-not (Test-Path -LiteralPath $IdentityFile)) {
    if (-not $CreateKey) {
        throw "Private key not found: $IdentityFile. Restore the existing key or rerun with -CreateKey to create a replacement key pair."
    }
    Write-Host "Creating a new Ed25519 key pair at $IdentityFile"
    & $sshKeygen -t ed25519 -f $IdentityFile -C 'codex-sentaurus-vm'
    if ($LASTEXITCODE -ne 0) { throw 'ssh-keygen failed.' }
}

$publicKeyPath = "$IdentityFile.pub"
if (-not (Test-Path -LiteralPath $publicKeyPath)) {
    Write-Host 'Public-key file is missing; deriving it from the private key.'
    $derivedPublicKey = & $sshKeygen -y -f $IdentityFile
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace(($derivedPublicKey -join ''))) {
        throw 'Could not derive the public key. If the private key has a passphrase, run ssh-keygen manually or load it into ssh-agent.'
    }
    ($derivedPublicKey -join "`n") | Set-Content -LiteralPath $publicKeyPath -Encoding ascii
}

$nativeConfig = @(
    '# Machine-local SSH configuration generated by setup.ps1.',
    'Host tcad-vm',
    "    HostName $HostAddress",
    "    Port $Port",
    "    User $UserName",
    '    StrictHostKeyChecking ask',
    '    ConnectTimeout 8',
    '    ServerAliveInterval 30',
    '    ServerAliveCountMax 3',
    ('    IdentityFile "' + $IdentityFile.Replace('\', '/') + '"'),
    '    IdentitiesOnly yes'
)
[IO.File]::WriteAllLines($localSshConfigPath, $nativeConfig, [Text.UTF8Encoding]::new($false))

$localConfig = [ordered]@{
    host = $HostAddress
    port = $Port
    username = $UserName
    identityFile = $IdentityFile
    vmName = $VmName
    vmxPath = $VmxPath
    vmrunPath = $VmrunPath
}
$localConfig | ConvertTo-Json | Set-Content -LiteralPath $localConfigPath -Encoding UTF8

$sshCommon = @(
    '-F', $localSshConfigPath,
    '-o', ('UserKnownHostsFile="{0}"' -f $knownHostsPath),
    '-o', 'StrictHostKeyChecking=ask'
)

if (-not $SkipAuthorize) {
    Write-Host 'The next SSH connection may ask for the TCAD2022 Linux password.'
    Write-Host 'The password is entered only in the terminal and is not stored.'
    # Avoid passing the public key as a shell argument: its spaces must remain intact.
    $installCommand = 'set -eu; umask 077; mkdir -p $HOME/.ssh; auth=$HOME/.ssh/authorized_keys; touch $auth; tmp=$(mktemp); cat > $tmp; if ! grep -qxF -f $tmp $auth; then cat $tmp >> $auth; fi; rm -f $tmp; chmod 700 $HOME/.ssh; chmod 600 $auth; printf KEY_READY\n'
    $publicKey = (Get-Content -LiteralPath $publicKeyPath -Raw -Encoding ascii).Trim()
    $publicKey | & $ssh @sshCommon '-o' 'PubkeyAuthentication=no' '-o' 'PreferredAuthentications=password,keyboard-interactive' 'tcad-vm' $installCommand
    if ($LASTEXITCODE -ne 0) { throw 'Public-key authorization failed.' }
}

Write-Host 'Testing non-interactive SSH authentication...'
$checkCommand = 'printf "KEY_AUTH_OK\n"; id -un; hostname'
& $ssh @sshCommon '-o' 'BatchMode=yes' '-o' 'StrictHostKeyChecking=yes' 'tcad-vm' $checkCommand
if ($LASTEXITCODE -ne 0) {
    throw 'SSH key authentication failed. Check the authorized key, private-key path, or ssh-agent.'
}

Write-Host "Local configuration saved to $localConfigPath"
Write-Host 'Run .\ssh.ps1 -Action Check and .\tcad.ps1 -Action Version to verify Sentaurus access.'
