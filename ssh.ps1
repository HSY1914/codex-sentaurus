[CmdletBinding()]
param(
    [ValidateSet('Status', 'Configure', 'Connect', 'Check')]
    [string]$Action = 'Status',
    [string]$UserName,
    [string]$IdentityFile,
    [string]$HostAddress,
    [ValidateRange(1, 65535)]
    [int]$Port
)

$ErrorActionPreference = 'Stop'
$baseConfigPath = Join-Path $PSScriptRoot 'connection.json'
$localConfigPath = Join-Path $PSScriptRoot 'connection.local.json'
$configPath = if (Test-Path -LiteralPath $localConfigPath) { $localConfigPath } else { $baseConfigPath }
$config = Get-Content -LiteralPath $configPath -Raw -Encoding UTF8 | ConvertFrom-Json
$ssh = (Get-Command ssh.exe -ErrorAction Stop).Source
$nativeConfigPath = if ($configPath -eq $localConfigPath) { Join-Path $PSScriptRoot 'ssh_config.local' } else { Join-Path $PSScriptRoot 'ssh_config' }

if ($Action -eq 'Configure') {
    if ($PSBoundParameters.ContainsKey('UserName')) {
        if ($UserName -notmatch '^[a-zA-Z_][a-zA-Z0-9_.-]*\$?$') { throw 'Invalid Linux username.' }
        $config.username = $UserName
    }
    if ($PSBoundParameters.ContainsKey('HostAddress')) {
        if ($HostAddress -notmatch '^[a-zA-Z0-9][a-zA-Z0-9.:-]*$') { throw 'Invalid host address.' }
        $config.host = $HostAddress
    }
    if ($PSBoundParameters.ContainsKey('Port')) { $config.port = $Port }
    if ($PSBoundParameters.ContainsKey('IdentityFile')) {
        if ($IdentityFile) {
            $config.identityFile = (Resolve-Path -LiteralPath $IdentityFile).Path
        } else { $config.identityFile = '' }
    }
    $config | ConvertTo-Json | Set-Content -LiteralPath $configPath -Encoding UTF8
    $nativeConfig = @(
        '# Project SSH configuration. Regenerated by ssh.ps1 -Action Configure.',
        'Host tcad-vm',
        "    HostName $($config.host)",
        "    Port $($config.port)",
        "    User $($config.username)",
        '    StrictHostKeyChecking ask',
        '    ConnectTimeout 8',
        '    ServerAliveInterval 30',
        '    ServerAliveCountMax 3'
    )
    if ($config.identityFile) {
        $nativeConfig += '    IdentityFile "' + $config.identityFile.Replace('\', '/') + '"'
        $nativeConfig += '    IdentitiesOnly yes'
    }
    [System.IO.File]::WriteAllLines($nativeConfigPath, $nativeConfig, [System.Text.UTF8Encoding]::new($false))
    Write-Output 'Configuration saved. No passwords are stored.'
    exit 0
}

if ($Action -eq 'Status') {
    Write-Output "VM: $($config.vmName)"
    Write-Output "Configured endpoint: $($config.host):$($config.port)"
    Write-Output "Username configured: $([bool]$config.username)"
    Write-Output "SSH client: $ssh"
    if (Test-Path -LiteralPath $config.vmrunPath) {
        $vmOutput = & $config.vmrunPath getGuestIPAddress $config.vmxPath 2>&1
        Write-Output "VMware address query (exit $LASTEXITCODE): $vmOutput"
    }
    $tcpClient = [System.Net.Sockets.TcpClient]::new()
    try {
        $connectionTask = $tcpClient.ConnectAsync([string]$config.host, [int]$config.port)
        if (-not $connectionTask.Wait(4000)) { throw 'TCP connection timed out.' }
        $stream = $tcpClient.GetStream()
        $stream.ReadTimeout = 4000
        $reader = [System.IO.StreamReader]::new($stream)
        $banner = $reader.ReadLine()
        if ($banner -notlike 'SSH-*') { throw "Unexpected SSH banner: $banner" }
        Write-Output "SSH service reachable: $banner"
        Write-Output 'This verifies the SSH service only, not login authentication.'
    } finally { $tcpClient.Dispose() }
    exit 0
}

if (-not $config.username) {
    throw 'Set your Linux username first: ./ssh.ps1 -Action Configure -UserName YOUR_LINUX_USER'
}

$knownHostsPath = (Join-Path $PSScriptRoot 'known_hosts').Replace('\', '/')
$sshArguments = @(
    '-p', [string]$config.port,
    '-l', [string]$config.username,
    '-o', 'ConnectTimeout=8',
    '-o', 'ServerAliveInterval=30',
    '-o', 'ServerAliveCountMax=3',
    '-o', ('UserKnownHostsFile="{0}"' -f $knownHostsPath)
)
if ($config.identityFile) {
    $sshArguments += @('-i', [string]$config.identityFile, '-o', 'IdentitiesOnly=yes')
}

if ($Action -eq 'Connect') {
    $sshArguments += @('-o', 'StrictHostKeyChecking=ask', [string]$config.host)
    & $ssh @sshArguments
    exit $LASTEXITCODE
}

# Read-only check. Host keys must already have been verified in an interactive connection.
$sshArguments += @(
    '-T', '-o', 'BatchMode=yes', '-o', 'StrictHostKeyChecking=yes',
    [string]$config.host,
    'hostname; id -un; uname -s; if command -v sdevice >/dev/null 2>&1; then command -v sdevice; else printf "sdevice not in non-interactive PATH\n"; fi'
)
& $ssh @sshArguments
exit $LASTEXITCODE
